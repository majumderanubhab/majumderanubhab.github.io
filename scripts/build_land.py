#!/usr/bin/env python3
"""Pre-compute the square land grids used by the journey & collaborator map.

The site draws the map from data/land.js, so it needs no mapping library at
runtime. Re-run this only if you change a view below.

Usage (from the repo root):
  1. Download the Natural Earth land outline (public domain), e.g.
     curl -L https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json -o /tmp/land-110m.json
  2. python3 scripts/build_land.py /tmp/land-110m.json
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "land.js"

# name: (west, east longitude), (north, south latitude), columns
VIEWS = {
    "world": ((-180, 180), (78, -56), 120),
    "europe": ((-12, 28), (62, 40), 60),
    "india": ((68, 96), (32, 6), 60),
}


def rings(topo):
    t = topo.get("transform")
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            if t:
                x += dx; y += dy
                pts.append((x * t["scale"][0] + t["translate"][0], y * t["scale"][1] + t["translate"][1]))
            else:
                pts.append((dx, dy))
        arcs.append(pts)

    def ring(idx):
        pts = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(a if not pts else a[1:])
        return pts

    out = []
    for g in topo["objects"]["land"]["geometries"]:
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
        for poly in polys:
            out.extend(ring(r) for r in poly)
    return out


def inside(rs, lon, lat):
    hit = False
    for r in rs:
        j = len(r) - 1
        for i in range(len(r)):
            xi, yi = r[i]; xj, yj = r[j]
            if abs(xi - xj) < 180 and (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                hit = not hit
            j = i
    return hit


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rs = rings(json.loads(pathlib.Path(sys.argv[1]).read_text()))
    views = {}
    for name, ((w, e), (n, s), cols) in VIEWS.items():
        rows_n = round(cols * (n - s) / (e - w))
        rows = []
        for r in range(rows_n):
            lat = n - (r + .5) * (n - s) / rows_n
            rows.append("".join("1" if inside(rs, w + (c + .5) * (e - w) / cols, lat) else "0" for c in range(cols)))
        views[name] = {"lon": [w, e], "lat": [n, s], "rows": rows}
        print(f"{name}: {cols}x{rows_n}, {sum(r.count('1') for r in rows)} land squares")
    OUT.write_text("/* Generated by scripts/build_land.py from Natural Earth land (public domain). Do not edit. */\n"
                   "window.LAND = " + json.dumps(views, separators=(",", ":")) + ";\n")
    print("Wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
